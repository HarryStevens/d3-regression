function shuffle(arr){
  var m = arr.length, t, i;
  while (m) {
    i = Math.floor(Math.random() * m--);
    t = arr[m];
    arr[m] = arr[i];
    arr[i] = t;
  }
  return arr;
}

it("loess.bandwidth(bandwidth) sets the bandwidth explicitly", () => {
  const r = d3.regressionLoess().bandwidth(.5);
  assert.strictEqual(r.bandwidth(), .5);
});

